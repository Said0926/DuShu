/*
 * busy.js — плашка «идёт подготовка» на время долгого запроса.
 *
 * «Чтение» переводит весь текст, Shadowing вдобавок озвучивает каждое предложение,
 * и оба делают это одним синхронным POST. До ответа браузер ничем не занят, и
 * страница выглядит зависшей — значит, сказать о работе должны мы сами.
 *
 * Долгой считается форма, отправленная кнопкой с data-busy. Именно кнопкой,
 * а не формой: у карточки ввода и у карточки в библиотеке форма одна, а адреса
 * два — второй приходит из formaction нажатой кнопки. Быстрые формы библиотеки
 * (переименовать, переместить, создать подборку) атрибута не несут, и плашки
 * у них нет: она соврала бы о долгой работе там, где её нет.
 *
 * Подпись лежит в значении того же атрибута, потому что ждут на двух страницах
 * разного — перевода или озвучки. Разметки в этом файле нет ни строчки: она
 * целиком в templates/includes/busy_overlay.html.
 */

const overlay = document.getElementById("busy");
const overlayTitle = document.getElementById("busy-title");

if (overlay && overlayTitle) {
  // Пауза перед показом. Закэшированный текст открывается за доли секунды,
  // и без неё плашка мигала бы при каждом повторном открытии. Отмеряем её
  // здесь, а не задержкой анимации в CSS: анимация может не проиграться,
  // и тогда плашка осталась бы невидимой, продолжая перехватывать клики.
  const SHOW_DELAY_MS = 150;

  // Ждём ли мы прямо сейчас ответ сервера. Пока ждём, вторую отправку не пропускаем:
  // она стоила бы второго обращения к DeepL и лишней единицы часового лимита.
  let waiting = false;
  let showTimer = null;

  /** Убирает плашку и возвращает форму в рабочее состояние. */
  function stopWaiting() {
    waiting = false;
    // Отменённая отправка не должна вытолкнуть плашку через полторы десятых
    // секунды после того, как её убрали.
    clearTimeout(showTimer);
    overlay.classList.remove("is-on");
  }

  // Одна подписка на весь документ: событие submit всплывает, поэтому форме
  // не нужно существовать в момент загрузки скрипта.
  document.addEventListener("submit", (event) => {
    // event.submitter — та самая кнопка, которой отправили форму. Запасной
    // вариант — атрибут на самой форме: он нужен смене языка в «Чтении»
    // (там requestSubmit() без аргумента, и submitter пустой) и заодно старым
    // браузерам, которые submitter не поддерживают.
    const label = (event.submitter && event.submitter.dataset.busy) || event.target.dataset.busy;

    if (!label) {
      // Быстрая форма — не наше дело.
      return;
    }

    if (waiting) {
      event.preventDefault();
      return;
    }

    waiting = true;
    showTimer = setTimeout(() => {
      // Класс раньше текста: скринридеры надёжно замечают изменение текста
      // внутри уже видимой live-области, а появление скрытой — как получится.
      overlay.classList.add("is-on");
      overlayTitle.textContent = label;
    }, SHOW_DELAY_MS);
  });

  // Safari и Firefox по кнопке «Назад» достают страницу из bfcache целиком —
  // вместе с уже показанной плашкой, и сайт выглядит зависшим. При обычной
  // загрузке эти же две строчки не меняют ничего: плашка и так скрыта.
  //
  // Из-за этого здесь нельзя заводить слушатели beforeunload и unload: они
  // отключают bfcache и оживляют ровно ту проблему, которую лечит pageshow.
  window.addEventListener("pageshow", stopWaiting);

  // Esc браузер понимает как «останови загрузку». Навигацию он отменит сам,
  // а нам остаётся снять плашку — иначе следующий клик упёрся бы в поднятый
  // флаг и не сделал бы ничего.
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && waiting) {
      stopWaiting();
    }
  });
}
